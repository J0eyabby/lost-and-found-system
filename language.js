    const applyLanguage = () => {
        const language = document.documentElement.lang || "en";
        const translationsForLanguage = translations[language];
        if (!translationsForLanguage) {
            return;
        }

        document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
        document.querySelectorAll("[data-i18n]").forEach((element) => {
            const translation = translationsForLanguage[element.dataset.i18n];
            if (translation) {
                element.textContent = translation;
            }
        });
        document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
            const translation = translationsForLanguage[element.dataset.i18nAria];
            if (translation) {
                element.setAttribute("aria-label", translation);
                element.setAttribute("title", translation);
            }
        });
        const phrases = interfacePhrases[language] || {};
        const searchPlaceholder = phrases["Search by item name"];
        if (searchPlaceholder) {
            document.querySelectorAll('input[placeholder="Search by item name"]').forEach((input) => {
                input.setAttribute("placeholder", searchPlaceholder);
            });
        }
        document.querySelectorAll("h1, h2, h3, a, button, label, option, p, strong, span, small").forEach((element) => {
            if (element.children.length > 0 || element.hasAttribute("data-i18n")) {
                return;
            }
            const originalText = element.textContent.trim();
            if (phrases[originalText]) {
                element.textContent = phrases[originalText];
            }
        });
    };

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", applyLanguage, { once: true });
    } else {
        applyLanguage();
    }
